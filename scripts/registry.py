#!/usr/bin/env python3
"""Run registry for the ICDE study: one row per prediction part (run x protocol x method stem x shard) from its
meta.json, with the provenance block written by run_baseline.py (benchmark version, code / scorer / tiles / manifest
sha, map version, visibility), counts (episodes, skipped with reasons, map_missing) and the reason for any test-fold run
(reports/icde/run_reasons.csv: run, stem, reason). Writes reports/icde/run_registry.csv and .md.

    python scripts/registry.py [--runs icde_v11 full_v1]
"""
import argparse
import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))
from cantraj import paths  # noqa: E402

OUT = os.path.join(paths.GPS_DIR, "reports", "icde")
FIELDS = ["benchmark_version", "baseline", "group", "protocol", "shard", "n_episodes", "n_skipped", "n_map_missing", "partial",
          "drives_done", "drives_total", "wall_s", "code_sha", "scorer_sha", "map_version", "tiles_manifest_sha", "map_episodes",
          "map_episodes_sha", "episode_visibility", "manifest_sha", "ckpt", "perturb", "warmup_s", "pf_tick_hz", "git"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", default=["icde_v11"])
    args = ap.parse_args()
    rows = []
    for run in args.runs:
        for mj in sorted(glob.glob(os.path.join(paths.PREDS, run, "*", "*.meta.json"))):
            m = json.load(open(mj))
            stem = os.path.basename(mj).split(".part")[0]
            sk = mj.replace(".meta.json", ".skipped.csv")
            reasons = ""
            row = {k: m.get(k) for k in FIELDS}
            if os.path.exists(sk):                 # the meta count covers every baseline of the invocation; count this stem's own file
                s = pd.read_csv(sk).drop_duplicates("episode_id", keep="last")
                reasons = "; ".join(f"{k} x{v}" for k, v in s.reason.str.slice(0, 60).value_counts().head(3).items())
                row["n_skipped"] = len(s)
            rows.append(dict(run=run, stem=stem, part=os.path.basename(mj).replace(".meta.json", ""), **row,
                             skipped_top=reasons, mtime=pd.Timestamp(os.path.getmtime(mj), unit="s").strftime("%Y-%m-%d %H:%M")))
    reg = pd.DataFrame(rows)
    rr = os.path.join(OUT, "run_reasons.csv")
    if os.path.exists(rr) and len(reg):
        reg = reg.merge(pd.read_csv(rr), on=["run", "stem"], how="left")
    os.makedirs(OUT, exist_ok=True)
    reg.to_csv(os.path.join(OUT, "run_registry.csv"), index=False)
    cols = [c for c in ["run", "protocol", "stem", "benchmark_version", "n_episodes", "n_skipped", "partial", "map_version",
                        "episode_visibility", "code_sha", "scorer_sha", "mtime", "reason"] if c in reg.columns]
    with open(os.path.join(OUT, "run_registry.md"), "w") as f:
        f.write("# Run registry (generated by scripts/registry.py; do not edit)\n\n")
        if not len(reg):
            f.write("(no parts yet)\n")
        else:
            try:
                f.write(reg[cols].to_markdown(index=False))
            except ImportError:                                   # no tabulate: plain pipe table
                sub = reg[cols].astype(str).replace("nan", "")
                f.write("| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n")
                for r in sub.itertuples(index=False):
                    f.write("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |\n")
    print(f"{len(reg)} parts -> {OUT}/run_registry.csv")


if __name__ == "__main__":
    main()
